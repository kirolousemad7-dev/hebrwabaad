        return [
            'sku' => $sku,
            'slug' => $slug,
            'name' => $name,
            'category' => $category,
            'short' => $short,
            'description' => $description,
            'specifications' => $specifications,
            'options' => array_map(fn (string $label) => ['name' => $label], $options),
            'seo_title' => $seoTitle,
            'seo_description' => $seoDescription,
        ];
    }
