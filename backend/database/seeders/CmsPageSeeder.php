    /**
     * @param  list<array{0: string, 1: string, 2?: string}>  $blocks
     */
    private function buildHtml(array $blocks): string
    {
        $html = [];

        foreach ($blocks as $block) {
            $tag = $block[0];
            $text = e($block[1]);

            if ($tag === 'p' && isset($block[2])) {
                $html[] = '<p><strong>'.$text.'</strong><br>'.e($block[2]).'</p>';

                continue;
            }

            $html[] = '<'.$tag.'>'.$text.'</'.$tag.'>';
        }

        return implode('', $html);
    }
