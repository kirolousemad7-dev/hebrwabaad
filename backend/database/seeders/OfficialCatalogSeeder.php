    private function seedServices(): void
    {
        foreach ($this->services() as $definition) {
            $service = Service::query()->firstOrNew(['slug' => $definition['slug']]);
            $existed = $service->exists;
            $price = $definition['base_price'] ?? null;
            $mode = $definition['pricing_mode'] ?? ($price === null ? CatalogPricingMode::Quote : CatalogPricingMode::Fixed);

            $service->fill([
                'name' => $definition['name'],
                'summary' => $definition['summary'],
                'description' => $definition['description'],
                'deliverables' => $definition['deliverables'] ?? [],
                'category' => $definition['category'],
                'subcategory' => $definition['subcategory'],
                'tags' => $definition['tags'] ?? [],
                'seo_title' => $definition['seo_title'] ?? $definition['name'],
                'seo_description' => $definition['seo_description'] ?? $definition['summary'],
                'og_title' => $definition['seo_title'] ?? $definition['name'],
                'og_description' => $definition['seo_description'] ?? $definition['summary'],
                'canonical_url' => $definition['canonical_url'] ?? '/services/'.$definition['slug'],
                'robots' => 'index,follow',
                'is_public' => true,
                'is_active' => true,
                'sort_order' => $definition['sort_order'] ?? 0,
            ]);

            $shouldSeedPrice = ! $existed
                || $service->pricing_mode === CatalogPricingMode::Quote
                || (float) $service->base_price <= 0.0;

            if ($shouldSeedPrice) {
                $service->fill([
                    'base_price' => $price ?? 0,
                    'currency' => 'SAR',
                    'pricing_mode' => $mode,
                    'duration_days' => $definition['duration_days'] ?? $service->duration_days,
                ]);
            }

            if (! $existed) {
                $service->is_featured = $definition['is_featured'] ?? false;
            }

            $service->save();
        }
    }

    private function seedPackages(): void
    {
        $definitions = collect(PackageSeeder::definitions())->keyBy('slug');

        foreach ($this->packages() as $slug => $copy) {
            $package = Package::query()->where('slug', $slug)->first();
            if ($package === null) {
                continue;
            }

            $package->fill($copy);
            $definition = $definitions->get($slug);
            if (is_array($definition) && array_key_exists('price', $definition)) {
                $package->price = $definition['price'];
                $package->pricing_mode = $definition['pricing_mode'] ?? $package->pricing_mode;
            }
            $package->save();
        }
    }

    private function seedSectors(): void
    {
        foreach ($this->sectors() as $slug => $copy) {
            $sector = Sector::query()->where('slug', $slug)->first();
            if ($sector === null) {
                continue;
            }

            $sector->fill($copy)->save();
        }
    }

